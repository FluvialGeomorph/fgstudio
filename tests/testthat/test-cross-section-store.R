test_that("optional overbanks round-trip mixed two, three and four vertex cross sections", {
  directory <- withr::local_tempdir()
  study <- file.path(directory,"study.gpkg");file.create(study)
  event <- file.path(directory,"event.gpkg");file.create(event)
  writeLines("points",file.path(directory,"points.gpkg"))
  context <- list(key="study",path=study,group_id="event",group_path=event)
  points <- list(path=directory,files=list(geopackage="points.gpkg"),inputs=list(hydro="sha"))
  store <- study_cross_section_store(function(key)study,function(key,event)context$group_path)
  f <- cross_section_review_fixture()
  line <- sf::st_sf(ReachName="R1",geometry=sf::st_sfc(sf::st_linestring(rbind(c(0,0),c(200,0))),crs=26915))
  fp <- sf::st_sf(geometry=sf::st_sfc(sf::st_polygon(list(rbind(
    c(0,-5),c(40,-5),c(40,-30),c(200,-30),c(200,30),c(80,30),c(80,5),c(0,5),c(0,-5)))),crs=26915))
  z <- fluvgeo::cross_section_layout(line,f$footprints$channel_outer,fp)
  settings <- list(channel=103,floodplain=109,spacing_m=20,tangent_distance_m=20,
    centerline_spacing_m=2,smoothing_refinements=2L,overbank_angle_limit_deg=30,allow_overbank_bends=TRUE)
  saved <- store$cross_section_publish(context,points,"r1",settings,z,
    list(channel_outer=f$footprints$channel_outer,floodplain_outer=fp),store$cross_section_inputs(context,points,"r1"))
  reopened <- store$cross_section_reopen(store$cross_section_read(context,points,"r1",settings))
  expect_setequal(vapply(sf::st_geometry(reopened$sections),nrow,integer(1)),2:4)
  expect_identical(reopened$sections$left_bank_vertex,z$sections$left_bank_vertex)
  expect_identical(reopened$sections$right_bank_vertex,z$sections$right_bank_vertex)
  expect_identical(reopened$sections$candidate_id,z$sections$candidate_id)
  expect_equal(sf::st_coordinates(reopened$sections),sf::st_coordinates(z$sections),ignore_attr=TRUE)
  expect_true(fluvgeo::check_cross_section_layout(reopened$sections,"candidate_table"))
  expect_true(all(reopened$sections$layout_channel_angle_limit_deg==30))
  expect_true(all(reopened$sections$layout_channel_rotation_review_deg==15))
  expect_identical(reopened$sections$channel_deconfliction_status,z$sections$channel_deconfliction_status)
  expect_identical(saved$schema,"FGSTUDIO_CROSS_SECTION_DRAFT_9")
  expect_true(all(c("channel_outer_raw","channel_reference_centerline","channel_branch_review") %in%
    sf::st_layers(file.path(saved$path,"cross-sections.gpkg"))$name))
  expect_identical(sf::st_as_binary(sf::st_geometry(reopened$source_channel)),
    sf::st_as_binary(sf::st_geometry(z$source_channel)))
  expect_identical(sf::st_as_binary(sf::st_geometry(reopened$channel_reference)),
    sf::st_as_binary(sf::st_geometry(z$channel_reference)))
  expect_identical(reopened$sections$left_geodesic_direction,z$sections$left_geodesic_direction)
  expect_identical(reopened$sections$right_group_routed,z$sections$right_group_routed)
  expect_identical(reopened$channel_branches$attachment_depth,z$channel_branches$attachment_depth)
  expect_identical(reopened$channel_branches$cleanup_status,z$channel_branches$cleanup_status)
  expect_identical(reopened$region_diagnostics$route_fragment_fallback,z$region_diagnostics$route_fragment_fallback)
  expect_identical(reopened$region_diagnostics$route_span_fraction,z$region_diagnostics$route_span_fraction)
})

test_that("standard cross_section drafts round-trip metadata and retain corrected identity", {
  directory <- withr::local_tempdir()
  study <- file.path(directory,"study.gpkg");file.create(study)
  event <- file.path(directory,"event.gpkg");file.create(event)
  point_path <- file.path(directory,"points.gpkg");writeLines("immutable points",point_path)
  context <- list(key="study",path=study,group_id="event",group_path=event)
  points <- list(path=directory,files=list(geopackage="points.gpkg"),inputs=list(hydro="sha"))
  store <- study_cross_section_store(function(key)study,function(key,event)context$group_path)
  f <- cross_section_review_fixture()
  settings <- list(channel=103,floodplain=106,spacing_m=20,tangent_distance_m=20,smoothing_refinements=2L,centerline_spacing_m=2,overbank_angle_limit_deg=30,allow_overbank_bends=TRUE)
  inputs <- store$cross_section_inputs(context,points,"r1")
  expect_null(store$cross_section_read(context,points,"r1"))
  saved <- store$cross_section_publish(context,points,"r1",settings,f$layout,f$footprints,inputs)
  path <- file.path(saved$path,"cross-sections.gpkg")
  expect_true(all(c("cross_section","layout_metadata","side_support") %in% sf::st_layers(path)$name))
  expect_true(all(c("hydraulic_regions","region_components","centerline","centerline_raw","centerline_skeleton","region_diagnostics") %in% sf::st_layers(path)$name))
  expect_true(all(c("boundary_chains","boundary_anchors") %in% sf::st_layers(path)$name))
  expect_true(all(sf::st_read(path,"boundary_anchors",quiet=TRUE)$candidate_id %in% saved$sections$candidate_id))
  expect_equal(nrow(sf::st_read(path,"hydraulic_regions",quiet=TRUE)),3)
  expect_false(any(grepl("^xs_[0-9]",sf::st_layers(path)$name)))
  expect_true(fluvgeo::check_cross_section_layout(sf::st_read(path,"cross_section",quiet=TRUE),"candidate_table"))
  metadata <- sf::st_read(path,"layout_metadata",quiet=TRUE)
  expect_identical(metadata$review_state,"draft")
  expect_match(metadata$settings_json,"spacing_m")
  reopened <- store$cross_section_read(context,points,"r1",settings)
  expect_identical(reopened$sections$candidate_id,f$layout$sections$candidate_id)
  expect_true(all(is.na(reopened$sections$layout_direction_window_m)))
  expect_equal(unique(reopened$sections$layout_tangent_distance_m),20)
  expect_equal(unique(reopened$sections$layout_smoothing_refinements),2L)
  expect_equal(unique(reopened$sections$layout_overbank_angle_limit_deg),30)
  expect_true(all(reopened$sections$layout_allow_overbank_bends))
  expect_equal(unique(reopened$sections$left_bank_vertex),2L)
  expect_identical(reopened$sections$left_leg_status,f$layout$sections$left_leg_status)
  expect_equal(reopened$sections$left_rotation_deg,f$layout$sections$left_rotation_deg)
  expect_identical(reopened$sections$left_short_tangent,f$layout$sections$left_short_tangent)
  expect_equal(sf::st_coordinates(reopened$sections),sf::st_coordinates(f$layout$sections),ignore_attr=TRUE)
  candidate <- store$cross_section_reopen(reopened)
  bent <- candidate
  xy <- sf::st_coordinates(bent$sections[1,])[,1:2]
  sf::st_geometry(bent$sections)[[1]] <- sf::st_linestring(rbind(xy[1,],
    (2*xy[1,]+xy[2,])/3,(xy[1,]+2*xy[2,])/3,xy[2:3,],colMeans(xy[3:4,]),xy[4,]))
  bent$sections$left_bank_vertex[1] <- 4L;bent$sections$right_bank_vertex[1] <- 5L
  bent$sections$left_bend_added[1] <- TRUE;bent$sections$right_bend_added[1] <- TRUE
  bent_saved <- store$cross_section_publish(context,points,"r1",settings,bent,f$footprints,inputs)
  bent_reopened <- store$cross_section_reopen(store$cross_section_read(context,points,"r1",settings))
  expect_equal(sf::st_coordinates(bent_reopened$sections[1,]),sf::st_coordinates(bent_saved$sections[1,]))
  expect_equal(bent_reopened$sections$left_bank_vertex[1],4L)
  expect_equal(bent_reopened$sections$left_bend_count[1],2L)
  expect_true(bent_reopened$sections$right_bend_added[1])
  candidate$sections <- candidate$sections[-2,]
  candidate$sections$Seq <- seq_len(nrow(candidate$sections))
  expect_error(store$cross_section_publish(context,points,"r1",settings,candidate,f$footprints,inputs),"current candidate identities")
  candidate$boundary_anchors <- candidate$boundary_anchors[candidate$boundary_anchors$candidate_id %in% candidate$sections$candidate_id,]
  xy <- sf::st_coordinates(candidate$sections[1,])[,1:2]
  xy[1,] <- c(50,-15)
  sf::st_geometry(candidate$sections)[[1]] <- sf::st_linestring(xy)
  candidate$sections$edited[1] <- TRUE
  corrected <- store$cross_section_publish(context,points,"r1",settings,candidate,f$footprints,inputs)
  expect_true(file.exists(path))
  expect_equal(corrected$sections$left_boundary_gap_m[1],15,tolerance=1e-6)
  expect_identical(corrected$sections$candidate_id[2],"sample-3")
  expect_null(store$cross_section_read(context,points,"another-reach"))
  old_directory <- file.path(dirname(saved$path),"old-loess-draft")
  dir.create(old_directory)
  old <- saved;old$inputs$schema <- "FGSTUDIO_CROSS_SECTION_INPUTS_1"
  old$parameters$method <- "exploratory-shortest-crossing-side-loess-v1"
  saveRDS(old,file.path(old_directory,"result.rds"))
  expect_false(identical(store$cross_section_read(context,points,"r1")$path,old_directory))
  expect_true(file.exists(file.path(old_directory,"result.rds")))
  previous_directory <- file.path(dirname(saved$path),"old-voronoi-draft")
  dir.create(previous_directory)
  previous <- saved;previous$inputs$method <- "polygon-centerline-v2"
  saveRDS(previous,file.path(previous_directory,"result.rds"))
  expect_false(identical(store$cross_section_read(context,points,"r1")$path,previous_directory))
  expect_true(file.exists(file.path(previous_directory,"result.rds")))
  previous$inputs$method <- "polygon-centerline-v10"
  saveRDS(previous,file.path(previous_directory,"result.rds"))
  expect_identical(inputs$method,"polygon-centerline-v11")
  expect_false(identical(store$cross_section_read(context,points,"r1")$path,previous_directory))
  expect_true(file.exists(file.path(previous_directory,"result.rds")))
  different <- settings;different$channel <- 104
  expect_null(store$cross_section_read(context,points,"r1",different))
  changed <- context;changed$group_path <- file.path(directory,"changed.gpkg");file.create(changed$group_path)
  expect_null(store$cross_section_read(changed,points,"r1"))
  writeLines("new points revision",point_path)
  expect_null(store$cross_section_read(context,points,"r1"))
  expect_error(store$cross_section_publish(context,points,"r1",settings,candidate,f$footprints,inputs),"Inputs changed")
})

test_that("cross-section drafts reject corrupt output and stale Study/Event revisions", {
  directory <- withr::local_tempdir()
  study <- file.path(directory,"study.gpkg");file.create(study)
  event <- file.path(directory,"event.gpkg");file.create(event)
  point_path <- file.path(directory,"points.gpkg");writeLines("points",point_path)
  context <- list(key="study",path=study,group_id="event",group_path=event)
  points <- list(path=directory,files=list(geopackage="points.gpkg"),inputs=list())
  current <- study;current_event <- event
  store <- study_cross_section_store(function(key)current,function(key,event)current_event)
  f <- cross_section_review_fixture()
  settings <- list(channel=103,floodplain=106,spacing_m=20,tangent_distance_m=20,smoothing_refinements=2L,centerline_spacing_m=2,overbank_angle_limit_deg=30,allow_overbank_bends=TRUE)
  inputs <- store$cross_section_inputs(context,points,"r1")
  saved <- store$cross_section_publish(context,points,"r1",settings,f$layout,f$footprints,inputs)
  writeLines("corrupt",file.path(saved$path,"cross-sections.gpkg"))
  expect_error(store$cross_section_read(context,points,"r1"),"changed")
  current <- "new-study.gpkg"
  expect_error(store$cross_section_publish(context,points,"r1",settings,f$layout,f$footprints,inputs),"Inputs changed")
  current <- study;current_event <- "new-event.gpkg"
  expect_error(store$cross_section_publish(context,points,"r1",settings,f$layout,f$footprints,inputs),"Inputs changed")
})
