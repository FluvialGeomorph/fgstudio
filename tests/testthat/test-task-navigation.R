  html <- as.character(mod_boundary_ui("test",study=list(boundary=TRUE)))
  expect_match(html,"Working on",fixed=TRUE)
  expect_match(html,'value="view" checked',fixed=TRUE)
  expect_false(grepl('id="test-edit_boundary"',html,fixed=TRUE))
  expect_false(grepl('id="test-define_stream"',html,fixed=TRUE))
